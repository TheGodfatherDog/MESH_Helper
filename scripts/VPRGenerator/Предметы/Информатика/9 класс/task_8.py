def generate_two_words_op():
    w1, w2 = random.choice(PAIRS_POOL)
    if random.choice([True, False]):
        w1, w2 = w2, w1

    scale = random.choice([1, 10, 50, 100])
    only_1 = random.randint(4, 35) * scale
    only_2 = random.randint(4, 35) * scale
    both = random.randint(2, 20) * scale

    n_1 = only_1 + both
    n_2 = only_2 + both
    n_and = both
    n_or = only_1 + only_2 + both

    find_and = random.choice([True, False])
    if find_and:
        rows = [
            [f"{w1} | {w2}", str(n_or)],
            [w1, str(n_1)],
            [w2, str(n_2)]
        ]
        target_q = f"{w1} & {w2}"
        ans = n_and
    else:
        rows = [
            [f"{w1} & {w2}", str(n_and)],
            [w1, str(n_1)],
            [w2, str(n_2)]
        ]
        target_q = f"{w1} | {w2}"
        ans = n_or

    random.shuffle(rows)

    prompt = (
        f"{HEADER_INTRO}\n"
        f"Какое количество страниц (в тысячах) будет найдено по запросу {target_q}? "
        "Считается, что все запросы выполнялись практически одновременно, так что набор страниц, "
        "содержащих все искомые слова, не изменялся за время выполнения запросов.\n"
        "Таблица запросов:"
    )

    return {
        "task": prompt,
        "table": {
            "headers": ["Запрос", "Найдено страниц (в тыс.)"],
            "rows": rows
        },
        "variants": None,
        "answer": str(ans)
    }

