# АРХЕТИП 3: ТРИ СЛОВА — ДИСТРИБУТИВНОСТЬ A & (B | C) (30%)
# =============================================================================

def generate_three_words_distrib():
    a, b, c = random.choice(TRIPLETS_SHARED_POOL)
    if random.choice([True, False]):
        b, c = c, b

    only_ab = random.randint(45, 280)
    only_ac = random.randint(45, 280)
    all_abc = random.randint(35, 190)

    n_ab = only_ab + all_abc
    n_ac = only_ac + all_abc
    n_abc = all_abc
    n_union = only_ab + only_ac + all_abc

    # Два варианта записи: A & (B | C) или (B | C) & A (как в примерах 20, 23, 6, 15)
    common_left = random.random() < 0.75
    if common_left:
        q_ab = f"{a} & {b}"
        q_ac = f"{a} & {c}"
        q_abc = f"{a} & {b} & {c}"
        q_union = f"{a} & ({b} | {c})"
    else:
        q_ab = f"{b} & {a}"
        q_ac = f"{c} & {a}"
        q_abc = f"{b} & {c} & {a}"
        q_union = f"({b} | {c}) & {a}"

    target_type = random.choices(["find_abc", "find_ac", "find_union"], weights=[0.40, 0.35, 0.25], k=1)[0]

    if target_type == "find_abc":
        rows = [[q_ab, str(n_ab)], [q_ac, str(n_ac)], [q_union, str(n_union)]]
        target_q, ans = q_abc, n_abc
    elif target_type == "find_ac":
        rows = [[q_ab, str(n_ab)], [q_abc, str(n_abc)], [q_union, str(n_union)]]
        target_q, ans = q_ac, n_ac
    else:
        rows = [[q_ab, str(n_ab)], [q_ac, str(n_ac)], [q_abc, str(n_abc)]]
        target_q, ans = q_union, n_union

    random.shuffle(rows)

    prompt = (
        f"{HEADER_INTRO}\n"
        f"Какое количество страниц (в тысячах) будет найдено по запросу {target_q}? "
        "Считается, что все запросы выполнялись практически одновременно, так что набор страниц, "
        "содержащих все искомые слова, не изменялся за время выполнения запросов.\n"
        "Таблица запросов:"
    )

    return {
        "task": prompt,
        "table": {
            "headers": ["Запрос", "Найдено страниц (в тыс.)"],
            "rows": rows
        },
        "variants": None,
        "answer": str(ans)
    }

