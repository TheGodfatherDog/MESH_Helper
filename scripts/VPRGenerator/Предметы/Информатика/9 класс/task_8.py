def generate_thousand_sites():
    w1, w2, w3 = random.choice(KEYWORDS_SITES_POOL)

    for _ in range(100):
        if random.choice([True, False]):
            # Пример 3 из Блока 3: w1 и w2 не пересекаются (w2 | w1 = n1 + n2)
            n1 = random.randint(15, 25) * 10
            n2 = random.randint(15, 25) * 10
            n3 = random.randint(30, 45) * 10
            n_or_12 = n1 + n2
            n_23 = random.randint(3, min(10, n2 // 10 - 2)) * 10
            n_13 = random.randint(3, min(10, n1 // 10 - 2)) * 10

            # Проверяем, что общее число сайтов в объединении <= 1000
            if (n1 + n2 + n3 - n_13 - n_23) > 980:
                continue

            ans = n_23 + n_13
            rows = [[w1, str(n1)], [w2, str(n2)], [w3, str(n3)]]
            prompt = (
                "Некоторый сегмент сети Интернет состоит из 1000 сайтов. Поисковый сервер в автоматическом режиме "
                "составил таблицу ключевых слов для сайтов этого сегмента.\n"
                f"Сколько сайтов будет найдено по запросу ({w2} | {w1}) & {w3}, если по запросу {w2} | {w1} было найдено "
                f"{n_or_12} сайтов; по запросу {w2} & {w3} — {n_23}, а по запросу {w1} & {w3} — {n_13}? "
                "Для обозначения операции «ИЛИ» используется символ «|», а для операции «И» — символ «&».\n"
                "Таблица ключевых слов:"
            )
        else:
            # Пример 16 из Блока 3: w1 | w3 = n1 + n3 и w2 & w3 = 0
            n1 = random.randint(18, 28) * 10
            n2 = random.randint(16, 24) * 10
            n3 = random.randint(30, 45) * 10
            n_12 = random.randint(6, min(14, min(n1, n2) // 10 - 2)) * 10
            n_or_13 = n1 + n3

            # Проверяем, что общее число сайтов в объединении <= 1000
            if (n1 + n2 + n3 - n_12) > 980:
                continue

            ans = n_12 + n3
            rows = [[w1, str(n1)], [w2, str(n2)], [w3, str(n3)]]
            prompt = (
                "Некоторый сегмент сети Интернет состоит из 1000 сайтов. Поисковый сервер в автоматическом режиме "
                "составил таблицу ключевых слов для сайтов этого сегмента.\n"
                f"Сколько сайтов будет найдено по запросу ({w1} & {w2}) | {w3}, если по запросу {w1} & {w2} было найдено "
                f"{n_12} сайтов; по запросу {w1} | {w3} — {n_or_13} сайтов, а по запросу {w2} & {w3} — 0 сайтов? "
                "Для обозначения операции «ИЛИ» используется символ «|», а для операции «И» — символ «&».\n"
                "Таблица ключевых слов:"
            )

        return {
            "task": prompt,
            "table": {
                "headers": ["Ключевое слово", "Количество сайтов"],
                "rows": rows
            },
            "variants": None,
            "answer": str(ans)
        }
    return None

