def plural_bytes(n):
    """Склонение слова 'байт' в конструкции 'на N байт(а) меньше/больше'."""
    n_abs = abs(n) % 100
    n_last = n_abs % 10
    if 11 <= n_abs <= 19:
        return f"{n} байт"
    if 2 <= n_last <= 4:
        return f"{n} байта"
    return f"{n} байт"

def build_unique_length_list(words_pool, min_count=6, max_count=9):
    """
    Формирует список слов, в котором КАЖДОЕ слово имеет строго уникальную длину,
    отсортированный по возрастанию длины (стандарт ФИПИ).
    """
    by_len = {}
    for w in words_pool:
        by_len.setdefault(len(w), []).append(w)

    available_lengths = sorted(by_len.keys())
    count = min(len(available_lengths), random.randint(min_count, max_count))
    chosen_lengths = sorted(random.sample(available_lengths, count))

    selected_words = [random.choice(by_len[length]) for length in chosen_lengths]
    return selected_words

def format_list_sentence(words, theme, use_colon_style):
    """Форматирует предложение со списком слов в одном из двух стилей ФИПИ."""
    display_words = list(words)
    if use_colon_style:
        return f"«{theme['colon_title']}: {', '.join(display_words)}»."
    else:
        # Первое слово в кавычках пишем с прописной буквы
        first = display_words[0]
        display_words[0] = first[0].upper() + first[1:]
        return f"«{', '.join(display_words)} — {theme['dash_title']}»."

