def generate_article_volume():
    while True:
        is_16bit = random.random() < 0.75
        bytes_per_char = 2 if is_16bit else 1

        pages = random.choice([4, 5, 6, 8, 10, 12, 15, 16, 20, 24, 32])
        lines = random.choice([16, 24, 32, 40, 48, 64])
        chars = random.choice([32, 40, 48, 60, 64])

        total_bytes = pages * lines * chars * bytes_per_char
        if total_bytes % 1024 == 0:
            kb_ans = total_bytes // 1024
            if 5 <= kb_ans <= 180:
                break

    if is_16bit:
        enc_phrase = "В одном из представлений Unicode каждый символ кодируется 16 битами."
    else:
        enc_name = random.choice(["КОИ-8", "Windows-1251"])
        enc_phrase = f"В кодировке {enc_name} каждый символ кодируется 8 битами."

    prompt = (
        f"Статья, набранная на компьютере, содержит {pages} страниц, на каждой странице {lines} строк, "
        f"в каждой строке {chars} символов. {enc_phrase} "
        "Определите информационный объём статьи в Кбайтах в этом варианте кодировки."
    )

    return prompt, str(kb_ans)

