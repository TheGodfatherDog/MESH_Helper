    theme = random.choice(THEMES_DB)

    words = build_unique_length_list(theme["words"], min_count=6, max_count=9)
    target_word = random.choice(words)

    # При вычёркивании слова из списка удаляется само слово + запятая + пробел (+2 символа)
    removed_chars = len(target_word) + 2
    delta_bytes = removed_chars * bytes_per_char
    bytes_str = plural_bytes(delta_bytes)

    use_colon = random.random() < 0.25
    sentence = format_list_sentence(words, theme, use_colon)

    if gender == "M":
        wrote_verb = "написал"
        actor_noun = "Ученик вычеркнул"
        pronoun_phrase = "Заодно он вычеркнул ставшие лишними запятые и пробелы"
    else:
        wrote_verb = "написала"
        actor_noun = "Ученица вычеркнула"
        pronoun_phrase = "Заодно она вычеркнула ставшие лишними запятые и пробелы"

    prompt = (
        f"{enc_text} {student_name} {wrote_verb} текст (в нём нет лишних пробелов):\n"
        f"{sentence}\n"
        f"{actor_noun} из списка название {theme['gen_one']}. "
        f"{pronoun_phrase} — два пробела не должны идти подряд. "
        f"При этом размер нового предложения в данной кодировке оказался на {bytes_str} меньше, "
        f"чем размер исходного предложения. Напишите в ответе вычеркнутое {theme['acc_target']}."
    )

    return prompt, target_word

